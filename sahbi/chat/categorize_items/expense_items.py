def _expand(words: set[str]) -> set[str]:
	out = {fold_arabic(w) if not w.isascii() else w for w in words}
	out |= {w[:-1] + "ى" for w in out if w.endswith("ي")}
	arabic = {w for w in out if not w.isascii()}
	out |= {"ال" + w for w in arabic if not w.startswith("ال")}
	return out


EXPENSE_ITEMS = _expand(_EXPENSE_BASE)


def is_expense_item(token: str) -> bool:
	if token in EXPENSE_ITEMS:
		return True
	# glued prefix on a definite noun: بالبنزين، للبنزين، والبنزين
	if token.startswith("لل") and "ال" + token[2:] in EXPENSE_ITEMS:
		return True
	if len(token) > 3 and token[0] in "وبلفك" and token[1:].startswith("ال") and token[1:] in EXPENSE_ITEMS:
		return True
	# possessives: يوميته، يوميتهم، فاتورته
	for suffix in ("ته", "تهم", "تها"):
		if token.endswith(suffix) and token[: -len(suffix)] + "ه" in EXPENSE_ITEMS:
			return True
	return False